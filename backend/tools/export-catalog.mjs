// Copies the product list from the website (src/menu.js + src/catalog.js) into the backend,
// so the server knows exactly which products exist. Run: npm run catalog
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import vm from "node:vm";

const here = dirname(fileURLToPath(import.meta.url));
const site = join(here, "..", "..", "src");
const sandbox = { window: {} };
sandbox.globalThis = sandbox.window;
vm.createContext(sandbox);
for (const f of ["menu.js", "catalog.js"]) vm.runInContext(readFileSync(join(site, f), "utf8"), sandbox, { filename: f });

const { SEREN_CATALOG: items, SEREN_CATEGORIES: categories } = sandbox.window;
if (!Array.isArray(items) || items.length === 0) throw new Error("Catalog came out empty: check src/menu.js");
const ids = new Set();
for (const it of items) {
  if (ids.has(it.id)) throw new Error(`Two products share the id "${it.id}"`);
  ids.add(it.id);
}
const body = `// Generated by tools/export-catalog.mjs from src/menu.js. Do not edit by hand.\n` +
  `export const CATEGORIES = ${JSON.stringify(categories, null, 2)};\n\n` +
  `export const CATALOG = ${JSON.stringify(items, null, 2)};\n`;
writeFileSync(join(here, "..", "src", "catalog.js"), body);
console.log(`catalog: ${items.length} products in ${Object.keys(categories).length} categories`);
